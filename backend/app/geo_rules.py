# -*- coding: utf-8 -*-
"""地名 assimilation 的共用判定规则——只留一份，避免各处重复定义后走样。

背景：这三份名单最早散在各脚本里各写各的。enrich_event_coords.py 里写死简体
「京师」，遇上图上的繁体写法「京師」就整个漏判——实测「至和元年日食」（1054 年，
京师＝北宋开封）差点被按 CBDB 唯一词条写成明代北京。

现在统一到这里，**并且比对前一律先繁简归一**。三份名单用途不同，别混用：

- `MOVABLE_CAPITAL`：任何档位都拦（严格档也拦）
- `CAPITAL_ALIAS`：只在**放宽年代窗口**时拦。严格档要求事件年份落在词条区间内，
  天然安全——按此写进去的「南京」227 条经审计全是明代事件，指向正确
- `BAD_ADDR`：CBDB 自身坐标错误的地址条目 id，任何情况都不采用
"""
from __future__ import annotations

from zhconv import convert as zh_convert

# 「随朝代搬家」的都城通称：同一个词在 CBDB 里只有一条跨数百年的坐标，但历史上
# 它指的地方随定都而变，写进去必错。实证：
#   京师 305 条，CBDB 全标北京(116.37,39.93)，可 1368~1420 年的明初京师是南京；
#   中都  25 条，CBDB 标山东汶上(116.48,35.73)，可 1153 年金中都在北京。
MOVABLE_CAPITAL = {
    "京师", "京城", "京都", "京阙", "京畿", "中都", "上都", "下都", "东京",
    "西京", "北都", "南都", "盛京", "兴京", "行在", "留都", "都城", "宸京",
}

# 放宽年代窗口（同名唯一但事件年份落在词条区间外）时，额外拦的一批
# 「后世才有的同名地名」。它们在 CBDB 里往往只有一条（明代的南京、清代的北京），
# 一旦年代不落在区间里，位置就一定不对：1127 年「迎康王即位」的南京是
# 应天府（今河南商丘），而词条指向明代南京。
CAPITAL_ALIAS = {
    "南京", "北京", "燕京", "汴京", "大都", "临安", "江宁", "应天", "顺天",
    "奉天", "庐州", "益州",
    # 安南：明清史料里的「安南」指今越南北部，CBDB 唯一词条却是清代贵州安南县；
    # 实测 6 条明代「安南之役」事件会全部被打到贵州（安顺一带），必须拦
    "安南",
}

# 看着像地名、其实不是具体地点的词，放宽档一律不用：
#   明堂 —— 礼制建筑名（都城里的明堂），CBDB 却有一条《明堂》县条目 668~907
#   西北路 —— 辽金「西北路招讨司」是军区不是城，坐标落在天山北麓
#   西都/东都 —— 方位性都城称谓，随政权而变。实测「西都」被 CBDB 别名指到江寧府
NON_PLACE = {"明堂", "西北路", "东北路", "西南路", "东南路", "西都", "东都",
             "西北", "东北", "西南", "东南", "江南", "江北", "关中", "关东",
             "关西", "岭南", "塞北", "漠北", "中原", "西域", "河北道", "河南道",
             # 河西：CBDB 里唯一带坐标的是元代云南河西县(102.64,24.14)，而图上
             # 124 条「河西」说的是河西走廊（武威—敦煌一带）。这是大区不是城。
             "河西", "河东", "河南地", "河套", "陇右", "山南", "淮南道"}

# 今天是省级/大区单位的名字：CBDB 里往往只有一条同名但位于别处的州/卫/路，
# 连上去就是把「某省发生的事」画成省内某一座城——误差以百公里计。
# 例：「广东」→《廣東衛》(广州)、「甘肃」→《甘肅衛》(张掖)、「西北」→《西北路》(阿尔泰)。
PROVINCE_LEVEL = {
    "广东", "广西", "河南", "河北", "山东", "山西", "陕西", "甘肃", "四川",
    "福建", "江西", "湖南", "湖北", "浙江", "江苏", "安徽", "海南", "云南",
    "贵州", "青海", "宁夏", "辽东", "辽西", "台湾", "西藏",
}

# 后缀归一化额外拦的两类 CBDB 条目：
#   卫所（admin=Wei）——只有明清才有，与地名义不同；且已发现《金齒衛》坐标错误
#     （本该在云南保山 99.2,25.1，被填到内蒙古 101.84,38.25）
#   带「省」字——现代省级单位的坐标其实是省会
SUFFIX_BLOCK_ADMIN = {"Wei"}


# 只在「忽略年代」的 stable/majority 档里拉黑的名字：这些地名的治所跨大区迁移过，
# 坐标随时代变，年代窗口一去掉就会张冠李戴（按年代匹配的档位不受影响——那里
# 年代是判据的一部分，本来就只会选中对应年代那条）：
#   扬州 —— 六朝治建康（南京），隋唐以后治江都（扬州）。图上 111 条事件跨越两朝
#   寿阳 —— 东晋避讳改「寿春」为寿阳，即今安徽寿县(116.78,32.58)；而 CBDB 的
#           《寿阳》是山西寿阳(113.17,37.89)。图上 88 条六朝事件会全跑到山西
#   金城 —— 汉金城郡是今兰州(103.8,36.05)；CBDB 的《金城》却是山西(113.18,39.56)。
#           「窦融入金城破先零羌」这类河西事件会差出 800 km
STABLE_BLOCK = {"扬州", "寿阳", "金城"}


def blocked_when_stable(name: str) -> bool:
    """忽略年代的档位专用红线：单字名不猜（「陈」既是国名也是朝代名），
    治所跨大区迁移过的名字不猜。"""
    return len(norm(name)) < 2 or norm(name) in STABLE_BLOCK


def prov_level(name: str) -> bool:
    """省级/大区名（做后缀归一化的前置红线）。"""
    return norm(name) in PROVINCE_LEVEL


def blocked_for_suffix(name: str, addr_name: str, addr_admin: str) -> bool:
    """后缀档专用红线：省级/大区名不猜，卫所条目不采用。"""
    return norm(name) in (MOVABLE_CAPITAL | CAPITAL_ALIAS | NON_PLACE
                          | PROVINCE_LEVEL) \
        or (addr_admin or "") in SUFFIX_BLOCK_ADMIN \
        or too_broad(addr_name)

# CBDB 自身坐标错误的地址条目，一律不用。每条都有实证：
#
#   4042《益州》908~1121 → 125.49,44.86（吉林）。益州历来是成都（104.07,30.67）。
#
#   3403/11167/14971/17162《登州》——四条带坐标的条目**全都共用《鄧州》的坐标**
#   112.08,32.68（河南邓州）。而「渤海靺鞨寇登州」等 34 条事件的登州是山东蓬莱。
#   CBDB 里坐标写对的只有《登州府》4945/8058（120.74,37.80），但只覆盖明清，
#   唐代事件取不到可用的正确坐标，所以整批不写——宁缺毋滥。
#
#   4257/11888/15418/301033《營州》——四条全部落在「河間/瀛州」那个点上
#   （116.09,38.44）。而「契丹寇营州」「安禄山任营州刺史」等 10 条事件的营州是
#   辽宁朝阳（120.45,41.57）。CBDB 里没有坐标正确的營州条目，整批不写。
#
#   12743《安國》——坐标与《臨安》完全相同（杭州）。而唯一那条事件是
#   「张安国杀耿京」，安国是**人名被误当地名**，根本不该有坐标。
#
#   12987《永興軍》977~978 → 115.21,29.83，那个坐标其实是「鄂州永興县/興國軍」
#   （湖北阳新，checklist：同坐标还挂着 興城、永興、興國軍）。而图上「赵思绾叛永兴」
#   等 10 条事件说的是五代永兴军，治所在长安。
BAD_ADDR = {"4042", "3403", "11167", "14971", "17162",
            "4257", "11888", "15418", "301033", "12743", "12987",
            # ── 整名字的坐标都不可信（抽查 stable/majority 档时发现）──
            #   16604/14194《龍城》109.25,24.54 —— 那是广西柳州；图上 44 条事件
            #   说的是前燕慕容氏的龙城，在辽宁朝阳（120.45,41.57）。
            #   15816/100163/18336/5382/7657《常山》118.5,28.9 —— 那是浙江常山县；
            #   常山郡是河北正定 / 元氏（114.5,38.1）。36 条事件会全错。
            #   15082/100167/600251《平城》113.1,37.4 —— 那是山西临汾一带；图上
            #   253 条事件全是「拓跋珪迁都平城」，平城是今大同（113.3,40.09）。
            "16604", "14194", "15816", "100163", "18336", "5382", "7657",
            "15082", "100167", "600251"}


def norm(name: str) -> str:
    """地名归一：繁体转简体 + 去首尾空白。比对名单前必须先过这一步。"""
    return zh_convert((name or "").strip(), "zh-cn")


def blocked_everywhere(name: str) -> bool:
    """任何档位都拉黑。"""
    return norm(name) in MOVABLE_CAPITAL


def blocked_when_relaxed(name: str) -> bool:
    """放宽年代窗口时才拉黑。"""
    return norm(name) in (MOVABLE_CAPITAL | CAPITAL_ALIAS | NON_PLACE)


def addr_is_bad(addr_id) -> bool:
    return str(addr_id) in BAD_ADDR


# 行政后缀：图上写法与 CBDB 词条常常只差这一个字（「建康」vs「建康府」、「代」vs「代州」）
SUFFIXES = ("郡", "縣", "县", "州", "府", "路", "道", "軍", "军", "城", "邑",
            "國", "国", "省", "鎮", "镇", "衛", "卫", "廳", "厅")

# 后缀归一化时的红线：
#   1) 单字地名（汉/赵/元/河/蜀）——「汉」在图上多半指汉朝或汉水，CBDB 却只有《汉州》
#      （四川广汉），照连必错，损失几百条也比写错强
#   2) 省级词条（陕西→陕西省，坐标落在西安）——把「在陕西省发生」画成「在西安发生」
#      是明知故犯的空间误差，不写
MIN_SUFFIX_LEN = 2


def suffix_variants(name: str) -> list[str]:
    """生成后缀变体：有后缀就剥掉，没有就试着补上。"""
    if len(name) < MIN_SUFFIX_LEN:
        return []
    out = []
    for s in SUFFIXES:
        if name.endswith(s) and len(name) > len(s):
            out.append(name[: -len(s)])
        else:
            out.append(name + s)
    return out


def too_broad(addr_name: str) -> bool:
    """省级单位：坐标其实是省会，用来指代整个省的事件误差太大。"""
    return (addr_name or "").endswith("省")
