# -*- coding: utf-8 -*-
"""地名 assimilation 的共用判定规则——只留一份，避免各处重复定义后走样。

背景：这三份名单最早散在各脚本里各写各的。enrich_event_coords.py 里写死简体
「京师」，遇上图上的繁体写法「京師」就整个漏判——实测「至和元年日食」（1054 年，
京师＝北宋开封）差点被按 CBDB 唯一词条写成明代北京。

现在统一到这里，**并且比对前一律先繁简归一**。三份名单用途不同，别混用：

- `MOVABLE_CAPITAL`：任何档位都拦（严格档也拦）
- `CAPITAL_ALIAS`：只在**放宽年代窗口**时拦。严格档要求事件年份落在词条区间内，
  天然安全——按此写进去的「南京」227 条经审计全是明代事件，指向正确
- `BAD_ADDR`：CBDB 自身坐标错误的地址条目 id，任何情况都不采用
"""
from __future__ import annotations

from zhconv import convert as zh_convert

# 「随朝代搬家」的都城通称：同一个词在 CBDB 里只有一条跨数百年的坐标，但历史上
# 它指的地方随定都而变，写进去必错。实证：
#   京师 305 条，CBDB 全标北京(116.37,39.93)，可 1368~1420 年的明初京师是南京；
#   中都  25 条，CBDB 标山东汶上(116.48,35.73)，可 1153 年金中都在北京。
MOVABLE_CAPITAL = {
    "京师", "京城", "京都", "京阙", "京畿", "中都", "上都", "下都", "东京",
    "西京", "北都", "南都", "盛京", "兴京", "行在", "留都", "都城", "宸京",
}

# 放宽年代窗口（同名唯一但事件年份落在词条区间外）时，额外拦的一批
# 「后世才有的同名地名」。它们在 CBDB 里往往只有一条（明代的南京、清代的北京），
# 一旦年代不落在区间里，位置就一定不对：1127 年「迎康王即位」的南京是
# 应天府（今河南商丘），而词条指向明代南京。
CAPITAL_ALIAS = {
    "南京", "北京", "燕京", "汴京", "大都", "临安", "江宁", "应天", "顺天",
    "奉天", "庐州", "益州",
    # 安南：明清史料里的「安南」指今越南北部，CBDB 唯一词条却是清代贵州安南县；
    # 实测 6 条明代「安南之役」事件会全部被打到贵州（安顺一带），必须拦
    "安南",
}

# 看着像地名、其实不是具体地点的词，放宽档一律不用：
#   明堂 —— 礼制建筑名（都城里的明堂），CBDB 却有一条《明堂》县条目 668~907
#   西北路 —— 辽金「西北路招讨司」是军区不是城，坐标落在天山北麓
#   西都/东都 —— 方位性都城称谓，随政权而变。实测「西都」被 CBDB 别名指到江寧府
NON_PLACE = {"明堂", "西北路", "东北路", "西南路", "东南路", "西都", "东都"}

# CBDB 自身坐标错误的地址条目，一律不用。每条都有实证：
#
#   4042《益州》908~1121 → 125.49,44.86（吉林）。益州历来是成都（104.07,30.67）。
#
#   3403/11167/14971/17162《登州》——四条带坐标的条目**全都共用《鄧州》的坐标**
#   112.08,32.68（河南邓州）。而「渤海靺鞨寇登州」等 34 条事件的登州是山东蓬莱。
#   CBDB 里坐标写对的只有《登州府》4945/8058（120.74,37.80），但只覆盖明清，
#   唐代事件取不到可用的正确坐标，所以整批不写——宁缺毋滥。
#
#   4257/11888/15418/301033《營州》——四条全部落在「河間/瀛州」那个点上
#   （116.09,38.44）。而「契丹寇营州」「安禄山任营州刺史」等 10 条事件的营州是
#   辽宁朝阳（120.45,41.57）。CBDB 里没有坐标正确的營州条目，整批不写。
#
#   12743《安國》——坐标与《臨安》完全相同（杭州）。而唯一那条事件是
#   「张安国杀耿京」，安国是**人名被误当地名**，根本不该有坐标。
BAD_ADDR = {"4042", "3403", "11167", "14971", "17162",
            "4257", "11888", "15418", "301033", "12743"}


def norm(name: str) -> str:
    """地名归一：繁体转简体 + 去首尾空白。比对名单前必须先过这一步。"""
    return zh_convert((name or "").strip(), "zh-cn")


def blocked_everywhere(name: str) -> bool:
    """任何档位都拉黑。"""
    return norm(name) in MOVABLE_CAPITAL


def blocked_when_relaxed(name: str) -> bool:
    """放宽年代窗口时才拉黑。"""
    return norm(name) in (MOVABLE_CAPITAL | CAPITAL_ALIAS | NON_PLACE)


def addr_is_bad(addr_id) -> bool:
    return str(addr_id) in BAD_ADDR
