_COMPILED = [(re.compile(p), n) for p, n in _RULES]

# 「被X」「为X所Y」「X于」这层壳要先剥掉，否则规则匹配不到内核
_STRIP = [
    (re.compile(r"^被"), ""),
    (re.compile(r"^见"), ""),
    (re.compile(r"^受(.*)于$"), r"\1"),
    (re.compile(r"(.*?)于$"), r"\1"),
    (re.compile(r"^为.*?所"), ""),
]


def normalize(rel: str | None) -> str | None:
    """把自由措辞的谓词归一到受控谓词；认不出来返回 None。"""
    if not rel:
        return None
    r = rel.strip()
    if not r:
        return None
    if r in EXACT:
        return EXACT[r]
    # 剥掉被动/「于」这类外壳再看
    cand = [r]
    for pat, rep in _STRIP:
        s = pat.sub(rep, r)
        if s and s != r and s not in cand:
            cand.append(s)
    for s in cand:
        if s in EXACT:
            return EXACT[s]
    for s in cand:
        for pat, canon in _COMPILED:
            if pat.search(s):
                return canon
    return None
